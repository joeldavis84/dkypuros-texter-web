from typing import Protocol


class MessagingTransport(Protocol):
    """Owned and called exclusively by a dedicated worker's main thread."""

    def start(self) -> None: ...
    def poll(self, timeout_ms: int = 100) -> None: ...
    def ready_to_send(self) -> bool: ...
    def send_text(self, recipient: str, body: str, message_id: int | None = None) -> None: ...
    def close(self) -> None: ...
